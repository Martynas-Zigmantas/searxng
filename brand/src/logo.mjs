// Alexandria logo: writes brand/logo/*, the theme's brand SVGs (favicon, PWA icons) and the inline template mark.
// Re-render:  PW=<path to playwright/index.mjs> [MARK=N1|N2] node brand/src/logo.mjs
import fs from 'node:fs';
import { C, MARK, mark, marks } from './mark.mjs';

const ROOT = new URL('../../', import.meta.url).pathname;
const OUT = `${ROOT}brand/logo/`;
const FONT = `${ROOT}client/simple/src/fonts/plus-jakarta-sans-latin-wght-normal.woff2`;
const svg = (inner, vb = '0 0 100 100') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">${inner}</svg>\n`;
const tile = (bg) => `<rect width="100" height="100" rx="22" fill="${bg}"/>`;
const files = {
  'app-icon.svg': svg(tile(C.plum) + mark(C.white, C.gold)),
  'app-icon-light.svg': svg(tile(C.white) + mark(C.plum, C.gold)),
  'favicon.svg': svg(tile(C.plum) + mark(C.white, C.gold, 8)),
  'mark-plum.svg': svg(mark(C.plum, C.gold), '14 14 72 72'),
  'mark-white.svg': svg(mark(C.white, C.gold), '14 14 72 72'),
};
fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(OUT)) fs.rmSync(OUT + f);
for (const [name, body] of Object.entries(files)) fs.writeFileSync(OUT + name, body);
fs.writeFileSync(`${ROOT}client/simple/src/brand/searxng-wordmark.svg`, files['favicon.svg']);
fs.writeFileSync(`${ROOT}client/simple/src/brand/searxng.svg`, files['mark-plum.svg']);
fs.writeFileSync(
  `${ROOT}searx/templates/simple/elements/brand_mark.html`,
  `{#- generated by brand/src/logo.mjs (mark ${MARK}), do not edit -#}\n<svg class="brand-mark" viewBox="14 14 72 72" aria-hidden="true">${mark('currentColor', 'var(--p-gold, #C9A24A)').replace(/\s+/g, ' ').trim()}</svg>\n`
);

// N2 needle = the loading spinner: inline template (currentColor) + two SVGs for the stock .loader (light/dark)
fs.writeFileSync(
  `${ROOT}searx/templates/simple/elements/needle_mark.html`,
  `{#- generated by brand/src/logo.mjs (loading needle, N2), do not edit -#}\n<svg class="needle-mark" viewBox="14 14 72 72" aria-hidden="true">${marks.N2('currentColor', 'var(--p-gold, #C9A24A)', 8).replace(/\s+/g, ' ').trim()}</svg>\n`
);
fs.writeFileSync(`${ROOT}client/simple/src/svg/needle-light.svg`, svg(marks.N2(C.plum, C.gold, 8), '14 14 72 72'));
fs.writeFileSync(`${ROOT}client/simple/src/svg/needle-dark.svg`, svg(marks.N2(C.white, C.gold, 8), '14 14 72 72'));

const { chromium } = await import(process.env.PW || 'playwright');
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1024, height: 1024 } });
for (const n of ['app-icon', 'app-icon-light', 'favicon']) {
  await p.setContent(`<body style="margin:0">${files[`${n}.svg`].replace('<svg ', '<svg width="1024" height="1024" ')}</body>`);
  await p.screenshot({ path: `${OUT}${n}.png`, omitBackground: true });
}
const face = `@font-face{font-family:Jakarta;font-weight:200 800;src:url(data:font/woff2;base64,${fs.readFileSync(FONT).toString('base64')}) format('woff2')}`;
for (const [n, bg, fg] of [['lockup-dark', C.plum, C.white], ['lockup-light', C.white, C.plum]]) {
  const q = await b.newPage({ viewport: { width: 1400, height: 400 } });
  await q.setContent(`<html><head><style>${face}</style></head><body style="margin:0;background:${bg};display:flex;align-items:center;justify-content:center;height:400px;gap:22px">
    <svg viewBox="14 14 72 72" width="170" height="170">${mark(fg, C.gold)}</svg><span style="font:800 130px Jakarta,sans-serif;letter-spacing:-0.05em;color:${fg}">Alexandria</span></body></html>`);
  await q.evaluate(() => document.fonts.ready);
  await q.screenshot({ path: `${OUT}${n}.png` });
  await q.close();
}
await b.close();
console.log(`alexandria logo (${MARK}) written`);
